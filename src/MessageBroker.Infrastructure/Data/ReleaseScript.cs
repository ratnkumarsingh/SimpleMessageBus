using System.Text;

namespace MessageBroker.Infrastructure.Data;

/// <summary>
/// Builds one SQL script that DBAs can review and apply in place of <see cref="SchemaDeployer"/>, for
/// hosts that run with Broker:Database:DeploySchemaOnStartup off. It brings a database at any version
/// up to date: each migration runs only when broker.SchemaVersions has no row for it and then writes
/// that row under the name DbUp uses, so a later DbUp deploy skips it. Programmability scripts are
/// CREATE OR ALTER and always run. Apply it with "sqlcmd -b" so the run stops at the first error.
/// </summary>
public static class ReleaseScript
{
    /// <summary>The database <see cref="BuildFull"/> creates and fills unless the person running it edits the name.</summary>
    public const string FullScriptDatabase = "BrokerDb";

    /// <summary>The settings at the top of <see cref="BuildFull"/>, each with its default.</summary>
    public static readonly IReadOnlyDictionary<string, string> FullScriptSettings = new Dictionary<string, string>
    {
        ["AdminName"] = "broker-admin",
        ["AdminApiKey"] = "",
        ["WebhookAllowedHosts"] = "",
    };

    public static string Build() => AppendSchema(new StringBuilder()
        .AppendLine("-- Internal Message Broker schema release script. Generated; do not edit.")
        .AppendLine("-- Apply with: sqlcmd -b -S <server> -d <database> -i <this file>")).ToString();

    /// <summary>
    /// A full install in one plain T-SQL file: creates the database when it is missing, applies
    /// <see cref="Build"/>, then adds the data the broker needs before anyone can call it, the same rows the
    /// broker's startup tasks add from Broker:Bootstrap and Broker:Webhooks:AllowedHosts. It runs as-is in
    /// SSMS or sqlcmd. The settings at the top reach the data batch through SESSION_CONTEXT, because local
    /// variables end at each GO. Re-running it is safe.
    /// </summary>
    public static string BuildFull()
    {
        var sql = new StringBuilder()
            .AppendLine("-- Internal Message Broker full install: database, schema and the data it needs to start.")
            .AppendLine("-- Generated by db/build-release-script.ps1 -Full from db/Migrations and db/Programmability.")
            .AppendLine("-- Edit only the settings below.")
            .AppendLine("--")
            .AppendLine("-- Run it in SSMS (connected to any database on the server) or with: sqlcmd -b -S <server> -i BrokerDb_Full.sql")
            .AppendLine("-- Running it again is safe: it applies only what is missing.")
            .AppendLine("-- Then add the applications that publish and receive with OnboardApplication.sql.")
            .AppendLine()
            .AppendLine("-- ===== Settings: edit these values before running")
            .AppendLine("SET QUOTED_IDENTIFIER ON;")
            .AppendLine("SET NOCOUNT ON;");
        foreach (var (name, value) in FullScriptSettings)
            sql.AppendLine($"EXEC sys.sp_set_session_context N'broker.{name}', N'{value}';");
        sql.AppendLine("-- AdminName            The Admin application. Admins manage topics, subscriptions and applications.")
           .AppendLine("-- AdminApiKey          Its API key. Leave it empty and the script generates one and shows it once, at the end.")
           .AppendLine("--                      Only the key's SHA-256 hash is stored, so keep the key in your secret store.")
           .AppendLine("-- WebhookAllowedHosts  Comma-separated hosts that webhook subscriptions may call, without scheme, port")
           .AppendLine("--                      or path, such as N'hooks.example.com,10.0.0.5'. For local development: N'localhost'.")
           .AppendLine($"-- Database name        To use another name, replace {FullScriptDatabase} in the two batches below.")
           .AppendLine("GO")
           .AppendLine($"IF DB_ID(N'{FullScriptDatabase}') IS NULL")
           .AppendLine("BEGIN")
           .AppendLine($"    PRINT N'Creating database {FullScriptDatabase}';")
           .AppendLine($"    CREATE DATABASE [{FullScriptDatabase}];")
           .AppendLine("END")
           .AppendLine("GO")
           .AppendLine($"USE [{FullScriptDatabase}];")
           .AppendLine("GO")
           .AppendLine();
        AppendSchema(sql);
        return sql.AppendLine()
            .AppendLine("-- ===== Data the broker needs to start")
            .AppendLine("SET NOCOUNT ON;")
            .AppendLine("BEGIN TRANSACTION;")
            .AppendLine()
            // COALESCE, not ISNULL: ISNULL would cut the default to the length of its first argument.
            .AppendLine("DECLARE @AdminName nvarchar(100) = COALESCE(NULLIF(LTRIM(RTRIM(CAST(SESSION_CONTEXT(N'broker.AdminName') AS nvarchar(100)))), N''), N'broker-admin');")
            .AppendLine("DECLARE @Key varchar(200) = COALESCE(LTRIM(RTRIM(CAST(SESSION_CONTEXT(N'broker.AdminApiKey') AS varchar(200)))), '');")
            .AppendLine("DECLARE @HostText nvarchar(4000) = COALESCE(CAST(SESSION_CONTEXT(N'broker.WebhookAllowedHosts') AS nvarchar(4000)), N'');")
            .AppendLine("DECLARE @Prefix varchar(32), @Hash varbinary(32), @NewKey varchar(100);")
            .AppendLine()
            .AppendLine("IF @AdminName COLLATE Latin1_General_BIN2 LIKE N'%[^-A-Za-z0-9._]%'")
            .AppendLine("    THROW 50400, N'AdminName may only hold letters, digits, ''.'', ''_'' and ''-''.', 1;")
            .AppendLine("IF EXISTS (SELECT 1 FROM broker.Applications WHERE Name = @AdminName AND IsAdmin = 0)")
            .AppendLine("    THROW 50409, N'AdminName belongs to an application that is not an Admin.', 1;")
            .AppendLine()
            .AppendLine("IF @Key <> ''")
            .AppendLine("BEGIN")
            .AppendLine("    IF LEN(@Key) < 18 OR LEFT(@Key, 4) COLLATE Latin1_General_BIN2 <> 'mbk_' OR SUBSTRING(@Key, 17, 1) <> '_'")
            .AppendLine("        THROW 50400, N'AdminApiKey is not a broker API key. Leave it empty to generate one.', 1;")
            // Keys are ASCII, so these bytes are the UTF-8 bytes ApiKeys.Hash hashes.
            .AppendLine("    SELECT @Prefix = LEFT(@Key, 16), @Hash = HASHBYTES('SHA2_256', @Key);")
            .AppendLine("END")
            // Generate a key only for an Admin that has none, so running the script again adds no keys.
            .AppendLine("ELSE IF NOT EXISTS (SELECT 1 FROM broker.Applications a JOIN broker.ApiKeys k ON k.AppId = a.AppId")
            .AppendLine("                    WHERE a.Name = @AdminName AND k.IsActive = 1)")
            .AppendLine("    EXEC broker.usp_ApiKey_Generate @NewKey OUTPUT, @Prefix OUTPUT, @Hash OUTPUT;")
            .AppendLine()
            .AppendLine("IF @Prefix IS NOT NULL")
            .AppendLine("BEGIN")
            .AppendLine("    DECLARE @AppId uniqueidentifier = NEWID(), @KeyId uniqueidentifier = NEWID();")
            .AppendLine("    EXEC broker.usp_Application_EnsureBootstrapAdmin @AppId, @AdminName, @KeyId, @Prefix, @Hash;")
            .AppendLine("END")
            .AppendLine()
            // Lower-cased like AdminService.NormalizeHost: a bare DNS name or IP address.
            .AppendLine("DECLARE @Hosts broker.HostList;")
            .AppendLine("INSERT @Hosts (Host)")
            .AppendLine("SELECT DISTINCT LOWER(LTRIM(RTRIM(value))) FROM STRING_SPLIT(@HostText, N',') WHERE LTRIM(RTRIM(value)) <> N'';")
            .AppendLine("IF EXISTS (SELECT 1 FROM @Hosts WHERE Host LIKE N'%[/ ]%' OR Host LIKE N'%://%')")
            .AppendLine("    THROW 50400, N'WebhookAllowedHosts takes host names or IP addresses without scheme, port or path.', 1;")
            .AppendLine("EXEC broker.usp_AllowedHost_Seed @Hosts;")
            .AppendLine()
            .AppendLine("COMMIT TRANSACTION;")
            .AppendLine()
            .AppendLine("IF @NewKey IS NOT NULL")
            .AppendLine("    PRINT N'New Admin API key, shown only now: ' + @NewKey;")
            .AppendLine("SELECT a.Name AS AdminName, k.Prefix AS KeyPrefix,")
            .AppendLine("       CASE WHEN k.Prefix = LEFT(@NewKey, 16) THEN @NewKey END AS NewApiKey,")
            .AppendLine("       (SELECT STRING_AGG(Host, N', ') FROM broker.WebhookAllowedHosts) AS WebhookAllowedHosts")
            .AppendLine("FROM broker.Applications a JOIN broker.ApiKeys k ON k.AppId = a.AppId")
            .AppendLine("WHERE a.Name = @AdminName AND k.IsActive = 1;")
            .AppendLine("GO")
            .ToString()
            // The file is committed (db/install/BrokerDb_Full.sql), so it must come out the same on every OS.
            .ReplaceLineEndings("\n");
    }

    private static StringBuilder AppendSchema(StringBuilder sql)
    {
        sql
           // sqlcmd starts with QUOTED_IDENTIFIER OFF, which filtered indexes reject; procedures also
           // keep the QUOTED_IDENTIFIER and ANSI_NULLS settings they were created with.
           .AppendLine("SET QUOTED_IDENTIFIER ON;")
           .AppendLine("SET ANSI_NULLS ON;")
           .AppendLine("SET ANSI_PADDING ON;")
           .AppendLine("SET ANSI_WARNINGS ON;")
           .AppendLine("SET ARITHABORT ON;")
           .AppendLine("SET CONCAT_NULL_YIELDS_NULL ON;")
           .AppendLine("SET NUMERIC_ROUNDABORT OFF;")
           .AppendLine("SET XACT_ABORT ON;")
           .AppendLine("SET NOEXEC OFF;")
           .AppendLine("GO")
           .AppendLine("IF SCHEMA_ID(N'broker') IS NULL EXEC(N'CREATE SCHEMA broker AUTHORIZATION dbo');")
           .AppendLine("GO")
           // The same table DbUp creates for its journal.
           .AppendLine("IF OBJECT_ID(N'broker.SchemaVersions', N'U') IS NULL")
           .AppendLine("    CREATE TABLE broker.SchemaVersions (")
           .AppendLine("        Id int IDENTITY(1,1) NOT NULL CONSTRAINT PK_SchemaVersions_Id PRIMARY KEY,")
           .AppendLine("        ScriptName nvarchar(255) NOT NULL,")
           .AppendLine("        Applied datetime NOT NULL);")
           .AppendLine("GO");

        foreach (var (name, script) in SchemaDeployer.ReadAllScripts())
        {
            sql.AppendLine().AppendLine($"-- ===== {name}");
            if (SchemaDeployer.IsMigration(name))
            {
                // NOEXEC spans batches, so it skips every GO-separated batch of an applied migration.
                var literal = name.Replace("'", "''", StringComparison.Ordinal);
                sql.AppendLine($"IF EXISTS (SELECT 1 FROM broker.SchemaVersions WHERE ScriptName = N'{literal}') SET NOEXEC ON;")
                   .AppendLine("GO")
                   .AppendLine("BEGIN TRANSACTION;")
                   .AppendLine("GO")
                   .AppendLine(script.TrimEnd())
                   .AppendLine("GO")
                   .AppendLine($"INSERT broker.SchemaVersions (ScriptName, Applied) VALUES (N'{literal}', GETDATE());")
                   .AppendLine("COMMIT TRANSACTION;")
                   .AppendLine("GO")
                   .AppendLine("SET NOEXEC OFF;")
                   .AppendLine("GO");
            }
            else
            {
                sql.AppendLine(script.TrimEnd()).AppendLine("GO");
            }
        }
        return sql;
    }
}
